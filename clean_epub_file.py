#!/usr/bin/env python3
import re
import os
import sys
import zipfile
import tempfile
from ebooklib import epub
from ebooklib.epub import EpubHtml

from textutils import clean_text_content

def clean_epub_file(input_epub):
    """
    Clean an EPUB file by removing extra dots between letters and .+ patterns.
    
    The output file name is automatically generated by appending '_cleaned' to the input file name.
    """
    # Create a temporary directory to work with the EPUB contents
    with tempfile.TemporaryDirectory() as temp_dir:
        try:
            # Extract the EPUB file (which is just a ZIP file)
            with zipfile.ZipFile(input_epub, 'r') as zip_ref:
                zip_ref.extractall(temp_dir)
            
            # Find and process all HTML/XHTML files
            for root, dirs, files in os.walk(temp_dir):
                for file in files:
                    if file.lower().endswith(('.html', '.htm', '.xhtml')):
                        file_path = os.path.join(root, file)
                        
                        try:
                            # Read the file content
                            with open(file_path, 'r', encoding='utf-8') as f:
                                content = f.read()
                            
                            # Clean the text content
                            cleaned_content = clean_text_content(content)
                            
                            # Write the cleaned content back
                            with open(file_path, 'w', encoding='utf-8') as f:
                                f.write(cleaned_content)
                                
                        except UnicodeDecodeError:
                            try:
                                # Try with a different encoding if UTF-8 fails
                                with open(file_path, 'r', encoding='latin-1') as f:
                                    content = f.read()
                                
                                # Clean the text content
                                cleaned_content = clean_text_content(content)
                                
                                # Write the cleaned content back
                                with open(file_path, 'w', encoding='latin-1') as f:
                                    f.write(cleaned_content)
                            except Exception as e:
                                print(f"Warning: Could not process file {file_path}: {e}")
            
            # Determine output file path
            base, ext = os.path.splitext(input_epub)
            output_epub = f"{base}_cleaned{ext}"
            
            # Create a new EPUB file with the cleaned contents
            with zipfile.ZipFile(output_epub, 'w', zipfile.ZIP_DEFLATED) as zip_ref:
                for root, dirs, files in os.walk(temp_dir):
                    for file in files:
                        file_path = os.path.join(root, file)
                        # Calculate the relative path for the ZIP archive
                        arcname = os.path.relpath(file_path, temp_dir)
                        zip_ref.write(file_path, arcname)
            
            print(f"Successfully cleaned EPUB file. Output saved to: {output_epub}")
            return True
            
        except Exception as e:
            print(f"Error processing EPUB file '{input_epub}': {e}")
            return False

def main():
    if len(sys.argv) != 2:
        print("Usage: python clean_epub_file.py <input_epub>")
        print("Example: python clean_epub_file.py ninestar4000.epub")
        print("The output file will be automatically created by appending '_cleaned' to the input file name.")
        return
    
    input_epub = sys.argv[1]
    
    # Check if the input file exists
    if not os.path.exists(input_epub):
        print(f"Error: Input file '{input_epub}' not found.")
        return
    
    # Check if the input file is an EPUB
    if not input_epub.lower().endswith('.epub'):
        print(f"Error: Input file '{input_epub}' is not an EPUB file.")
        return
    
    clean_epub_file(input_epub)

if __name__ == "__main__":
    main()